import { readdir } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import type { CodegenRecipe } from "codegen";
import { defineCodegen, runCodegen } from "codegen";

import { assembleSystemPrompt } from "../../../assembly";
import { body as grammarBody } from "./prompt-part/grammatical-resolution/de/lexeme/noun/body";
import { examplesToUse as grammarExamples } from "./prompt-part/grammatical-resolution/de/lexeme/noun/examples-to-use";
import { inputSchema as grammarInputSchema } from "./prompt-part/grammatical-resolution/de/lexeme/noun/input-schema";
import { outputSchema as grammarOutputSchema } from "./prompt-part/grammatical-resolution/de/lexeme/noun/output-schema";
import { body as readingBody } from "./prompt-part/reading-resolution/de/lexeme/noun/body";
import { examplesToUse as readingExamples } from "./prompt-part/reading-resolution/de/lexeme/noun/examples-to-use";
import { inputSchema as readingInputSchema } from "./prompt-part/reading-resolution/de/lexeme/noun/input-schema";
import { outputSchema as readingOutputSchema } from "./prompt-part/reading-resolution/de/lexeme/noun/output-schema";

const experimentRoot = dirname(fileURLToPath(import.meta.url));
const promptPartRoot = join(experimentRoot, "prompt-part");
const generatedRoot = join(experimentRoot, "generated-system-prompt");
const expectedPartFiles = [
	"body.ts",
	"examples-for-test.ts",
	"examples-to-use.ts",
	"input-schema.ts",
	"output-schema.ts",
] as const;

const promptSources = [
	{
		route: "grammatical-resolution/de/lexeme/noun",
		inputSchema: grammarInputSchema,
		outputSchema: grammarOutputSchema,
		body: grammarBody,
		examplesToUse: grammarExamples,
	},
	{
		route: "reading-resolution/de/lexeme/noun",
		inputSchema: readingInputSchema,
		outputSchema: readingOutputSchema,
		body: readingBody,
		examplesToUse: readingExamples,
	},
] as const;

type CompactPromptRecipe = CodegenRecipe<
	Record<never, never>,
	{ readonly generated: { readonly root: string } },
	{ readonly route: string }
>;

export const compactSystemPromptRecipe: CompactPromptRecipe = defineCodegen<
	Record<never, never>,
	{ readonly generated: { readonly root: string } },
	{ readonly route: string }
>({
	inputs: {},
	outputs: { generated: { root: generatedRoot } },
	async build() {
		await assertPromptSourceLayout();
		return promptSources.map((source) => ({
			id: `issue-22-compact-system-prompt:${source.route}`,
			to: { target: "generated" as const, path: `${source.route}.ts` },
			content: renderModule(assembleSystemPrompt(source)),
			provenance: expectedPartFiles
				.filter((file) => file !== "examples-for-test.ts")
				.map((file) => ({
					kind: "source" as const,
					path: join(promptPartRoot, source.route, file),
				})),
			meta: { route: source.route },
		}));
	},
});

async function assertPromptSourceLayout(): Promise<void> {
	for (const source of promptSources) {
		const directory = join(promptPartRoot, source.route);
		const actualFiles = (await readdir(directory, { withFileTypes: true }))
			.filter((entry) => entry.isFile())
			.map((entry) => entry.name)
			.toSorted();
		if (actualFiles.join("\n") !== expectedPartFiles.join("\n")) {
			throw new Error(
				`Issue #22 Prompt Source "${source.route}" must contain exactly ${expectedPartFiles.join(", ")}; found ${actualFiles.join(", ") || "no files"}.`,
			);
		}
	}
}

function renderModule(systemPrompt: string): string {
	return `// Generated by issue-22-compact-noun-dtos/generate-system-prompts.ts. Do not edit.\n\nexport const systemPrompt = ${JSON.stringify(systemPrompt)};\n`;
}

if (import.meta.main) {
	const mode = process.argv.includes("--check") ? "check" : "write";
	const result = await runCodegen(compactSystemPromptRecipe, { mode });
	if (mode === "check" && result.status === "changed") {
		const stale = result.plan.changes
			.filter((change) => change.kind !== "unchanged")
			.map((change) => relative(experimentRoot, change.destination));
		console.error(
			`Issue #22 generated system prompts are stale: ${stale.join(", ")}`,
		);
		process.exitCode = 1;
	}
}
